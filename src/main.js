import kaplay from "kaplay";
import { WIDTH, HEIGHT } from "./config.js";
import { gameScene } from "./scenes/game.js";
import { menuScenes } from "./scenes/menus.js";
import { cutsceneScene } from "./scenes/cutscene.js";
import { initAudio } from "./systems/audio.js";
import { loadStoryArt } from "./story/art.js";

const k = kaplay({
    width: WIDTH,
    height: HEIGHT,
    letterbox: true,
    background: [0, 0, 0], // outside the map is pitch black (floor colour is drawn per map)
    global: false,
    font: "handpixies", // default font for every text (loaded below)
    texFilter: "nearest", // crisp pixel art when scaled
    crisp: true, // no antialiasing / smoothing of the scaled canvas
});

// Right mouse button toggles the flashlight -> no browser context menu.
k.canvas.addEventListener("contextmenu", (e) => e.preventDefault());

k.loadRoot("./");
// HandPixies by HeavenCastro (public domain), with Polish letters and fixed metrics
// added by scripts/build-font.py. Renders at about half the size given (see FONT in config.js).
k.loadFont("handpixies", "fonts/HandPixies-PL.ttf", { filter: "nearest" });
// Extraction close-up art (optional, placeholders are drawn when missing).
// Sizes on screen: pc_panel / pc_board 360x240, pc_ram 200x30, pc_screw 24x24
// Draw them 1:1 in these sizes, or exactly half (180x120, 100x15, 12x12) for chunky 2x pixels.
k.loadSprite("pc_panel", "sprites/pc_panel.png");
k.loadSprite("pc_board", "sprites/pc_board.png");
k.loadSprite("pc_panel_swipe", "sprites/pc_panel_swipe.png"); // panel art shown during the "slide" stage
k.loadSprite("pc_ram", "sprites/pc_ram.png");
k.loadSprite("pc_panel_arrows", "sprites/pc_panel_with_guiding_arrows.png"); // panel art for the screw stage
// k.loadSprite("pc_screw", "sprites/pc_screw.png");
// Characters (generated by scripts/make-sprites.py from tiles/): 32x32 frames.
k.loadSprite("player", "sprites/player.png", { sliceX: 4, sliceY: 4 }); // rows: down, up, right, left
k.loadSprite("teacher", "sprites/teacher.png", { sliceX: 4, sliceY: 8 }); // idle d/l/r/u, walk d/l/r/u
k.loadSprite("mieciu", "sprites/mieciu.png", { sliceX: 4, sliceY: 8 }); // Pan Mieciu, same layout
// Room art (see `background` in src/level/rooms.js). Square Tiled exports are fine:
// the sprite is drawn at its natural size from the top-left corner, transparent padding is ignored.
k.loadSprite("level2", "sprites/level2.png");
k.loadSprite("level_jammed", "sprites/level_jammed.png"); // built by scripts/build-level-art.py
k.loadSprite("level_lounge", "sprites/level_lounge.png");
// Portraits and cutscene sprites are drawn in code (src/story/art.js).
loadStoryArt(k);
// Music + SFX are synthesized (Web Audio), no files. Starts on the first click / key.
initAudio();

// Dev only: access the engine from the browser console (e.g. __k.get("player")[0]).
if (import.meta.env.DEV) window.__k = k;

// Draw order: world (map, characters) -> dark (fog) -> glow (visible in the dark) -> ui.
// setLayers may only be called once, so it lives here and not in a scene.
k.setLayers(["world", "dark", "glow", "ui"], "world");

menuScenes(k);
cutsceneScene(k);
gameScene(k);

k.go("menu");
